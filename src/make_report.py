"""Assemble docs/RESULTS.md from the summary JSONs and tables written by each RQ step.
Every number in the report is read from pipeline outputs, so re-running regenerates it."""
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from riskshift import config as C  # noqa: E402
from riskshift.common import banner, short  # noqa: E402

S = C.OUT / "summary"


def j(name):
    return json.loads((S / f"{name}.json").read_text())


def md(df: pd.DataFrame, floatfmt=2) -> str:
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:.{floatfmt}f}")
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep] + rows)


def main():
    banner("make_report")
    r1, r2, r3 = j("rq1"), j("rq2"), j("rq3")
    r4s, r4i, r4m = j("rq4_stability"), j("rq4_interpretation"), j("rq4_migration")
    T = lambda n: pd.read_csv(C.TABLES / f"{n}.csv")  # noqa: E731
    out = []
    w = out.append

    w("# RiskShift-India: results\n")
    w(f"*Generated by `src/make_report.py` from pipeline outputs. {C.DISCLAIMER}*\n")
    w("Data: GBD 2023 S14B, risk-attributable deaths for India and 31 state units, 1990/2010/2023. "
      "Every number below comes from `outputs/tables` and `outputs/summary`. The methods are in `docs/rules_log.md`.\n")

    # ------------------------------------------------ headline
    tc = r1["tier_counts"]
    s20 = r2["success_criterion"]
    lab20 = [x for x in r3["sensitivity_summary"] if x["N"] == 20 and x["family"] == "overall"][0]
    w("## Headline answers\n")
    w(f"| RQ | Answer |\n| --- | --- |\n"
      f"| RQ1: worsening and divergence | Of {r1['n_pairs']} Core state × risk pairs, {r1['point_up']} rose from 2010 to 2023, but only "
      f"**{tc.get('Clear worsening', 0)} are clear worsening** (interval wholly above zero). {r1['clear_by_risk'].get('High body-mass index', 0)} of those are high BMI and "
      f"{r1['clear_by_risk'].get('High fasting plasma glucose', 0)} are high fasting glucose. Another {tc.get('Possible worsening', 0)} are possible worsening, and "
      f"{tc.get('Adverse divergence', 0)} fell at least 10 pp less than India. |\n"
      f"| RQ2: does trend-aware ranking surface new cases? | **Yes, by the pre-set criterion.** The cross-risk score with a materiality floor puts "
      f"{s20['new_clear_material']} clear-worsening, material, non-small-base pairs into the top 20 that neither burden ranking has. The success threshold was {C.SUCCESS_MIN_NEW}. "
      f"The proposed within-risk scaling also looks novel, but {r2['within_top20_below_floor']} of its top 20 fall below the floor. That is partly a scaling artefact. |\n"
      f"| RQ3: how stable are the ranks? | Under weights and risk selection, most top-20 pairs hold. Under GBD uncertainty, few do. Overall labels for the top 20: "
      f"**{lab20['Robust']} Robust, {lab20['Moderate']} Moderate, {lab20['Fragile']} Fragile**. GBD uncertainty is the binding constraint. |\n"
      f"| RQ4: are there robust state clusters? | **No: a gradient, not clusters.** {r4s['all31']['verdict_counts'].get('Gradient, not clusters', 0)} of 24 configurations reach "
      f"\"gradient\". Only {r4s['all31']['gate1_pass']} beat the no-cluster null, and the median ARI across configurations is {r4s['all31']['median_cross_config_ari']:.2f}. "
      f"Small stable cores do exist, and over 1990–2023 states move from a traditional-risk profile to a metabolic one. |\n")

    # ------------------------------------------------ RQ1
    w("## RQ1: which pairs worsened, and which diverged from India?\n")
    nat = r1["india_clearly_rising"]
    w("Nationally, only " + " and ".join(f"{d['risk']} ({d['pct_2010_23_mean']:+.1f}%, UI {d['pct_2010_23_lo']:+.1f} to {d['pct_2010_23_hi']:+.1f})" for d in nat)
      + " show a clear rise among the level-2 risks.\n")
    cr = T("rq1_tier_counts_by_risk")
    cr = cr[(cr[["Clear worsening", "Possible worsening", "Adverse divergence"]].sum(axis=1) > 0)]
    w(md(cr.sort_values("Clear worsening", ascending=False)) + "\n")
    w(f"* Of the watchlist pairs, {r1['watchlist_small_base']} have a small base (2010 ASR < 5), and {r1['recent_reversal_in_watchlist']} reverse the 1990–2023 direction.")
    ts = r1["threshold_sensitivity"]
    w(f"* The divergence threshold matters. At 5 / 10 / 15 pp, the adverse-divergence tier holds "
      f"{ts['5 pp']['Adverse divergence']} / {ts['10 pp']['Adverse divergence']} / {ts['15 pp']['Adverse divergence']} pairs.")
    w("* Without Other UTs, the tier counts are " + ", ".join(f"{k} {v}" for k, v in r1["without_other_uts"].items()) + ".")
    dn = T("rq1_detail_national")
    dn = dn[dn.india_lo > 0].sort_values("india_asr_2023", ascending=False)
    w("* Detail set: inside the level-2 signals, the risks rising clearly at national level are "
      + "; ".join(f"{r.detail_risk} ({r.india_pct:+.1f}%, {r.states_clear} states clear)" for r in dn.itertuples())
      + ". Ambient PM is rising while household air pollution falls, so the two cancel inside the falling air-pollution total.\n")
    wl = T("rq1_watchlist_core")
    w("Top clear-worsening pairs by absolute change:\n")
    w(md(wl[wl.tier == "Clear worsening"].head(12)[["location", "risk", "asr_2010_mean", "asr_2023_mean", "pct_2010_23_mean", "pct_2010_23_lo", "india_pct_2010_23"]], 1) + "\n")
    w("Figures: `outputs/figures/rq1_heatmap_core.png` and `rq1_dumbbells_core.png`. Full lists: `outputs/tables/rq1_watchlist_core.csv` (with reasons) and `rq1_watchlist_detail.csv`.\n")
    w("*Caveat: tiers are descriptive labels built from GBD intervals, not significance tests.*\n")

    # ------------------------------------------------ RQ2
    w("## RQ2: does trend-aware prioritisation surface different cases?\n")
    comp = T("rq2_comparison_all")
    w(md(comp[["variant", "N", "overlap_B1", "overlap_B2", "jaccard_B1", "jaccard_B2", "n_new", "new_clear", "new_clear_material",
               "new_small_base", "new_below_floor", "spearman_B2", "kendall_B2"]]) + "\n")
    w(f"**Success criterion** ({s20['rule']}): {s20['new_clear_material']} qualifying pairs. Met: **{s20['met']}**.\n")
    w("Overlooked pairs (in the cross-risk top 20, absent from both burden top 20s):\n")
    ov = pd.DataFrame(r2["overlooked_N20"])
    w(md(ov[["location", "risk", "tier", "asr_2023_mean", "abs_2010_23", "why_surfaced"]], 1) + "\n")
    w(f"The within-risk score (min-max per risk, as proposed) overlaps B2 by only {int(comp[(comp.variant.str.startswith('within')) & (comp.N == 20)].overlap_B2.iloc[0])} of 20. "
      f"But {r2['within_top20_below_floor']} of its top 20 are below the materiality floor, for example drug use in Uttarakhand, Arunachal Pradesh and Chhattisgarh. "
      "Within-risk scaling gives every risk's worst state a score near 1, however small the risk. Use it only to rank states within one risk "
      "(`rq2_within_risk_state_rankings.csv`).\n")
    w("The cross-risk novelty is not noise-driven: no new pair has a small base, and none is below the floor. "
      "Most new entries are blood pressure and dietary risks in high-burden states where the rate rose while India's fell.\n")

    # ------------------------------------------------ RQ3
    w("## RQ3: how stable are the rankings?\n")
    ss = pd.DataFrame(r3["sensitivity_summary"])
    w(md(ss.pivot_table(index=["N", "family"], values=["Robust", "Moderate", "Fragile"]).reset_index()[["N", "family", "Robust", "Moderate", "Fragile"]], 0) + "\n")
    kt = pd.DataFrame(r3["kendall"])[["family", "scenarios", "kendall_median", "kendall_p05", "kendall_min"]]
    w("Kendall's tau between the base ranking and each perturbed ranking (all 620 pairs):\n")
    w(md(kt) + "\n")
    t20 = pd.DataFrame(r3["top20"])
    w(md(t20[["base_rank", "location", "risk", "Weights_freq_top20", "Uncertainty_freq_top20", "Selection_freq_top20", "overall_label"]]) + "\n")
    tf = pd.DataFrame(r3["tier_flips"])
    w("RQ1 tier flips:\n")
    w(md(tf) + "\n")
    w("Reading: weights and risk selection rarely change who is in the top 20. GBD uncertainty does, because the 2010–23 change intervals are wide. "
      "Even so, Bihar's air pollution, blood pressure and dietary risks stay in the top 20 under at least 80% of uncertainty draws. "
      "Clear-worsening tiers never flip, because they are defined by the interval. Adverse-divergence tiers flip in about half of the draws. "
      "The draws are independent per cell (IHME's posterior draws are not public), so this is a conservative stress test, not a posterior.\n")
    w("Figure: `outputs/figures/rq3_rank_ranges.png`.\n")

    # ------------------------------------------------ RQ4
    a = r4s["all31"]
    w("## RQ4: do compact, interpretable, stable state clusters exist?\n")
    fmt = lambda d: ", ".join(f"{k} {v}" for k, v in d.items())  # noqa: E731
    w(f"**Verdict: gradient, not clusters** (31 units: {fmt(a['verdict_counts'])}; without Other UTs: {fmt(r4s['no_other_uts30']['verdict_counts'])}).\n")
    dec = T("rq4_decision_table")
    d31 = dec[dec.units == "all31"][["config", "k_star", "observed_best_sil", "null_mvn_p95", "gate1_existence", "boot_jaccard_min",
                                      "median_ari_vs_other_configs", "unc_ari_median", "loro_ari_median", "verdict"]]
    w(md(d31) + "\n")
    ks = T("rq4_k_selection")
    w(f"* **4a Existence.** The gap statistic chooses k = 1 in {int((ks.k_gap == 1).sum())} of {len(ks)} configurations. "
      f"Only {a['gate1_pass']}/24 configurations clear gate 1 (silhouette ≥ 0.25 and above the 95th percentile of the multivariate-normal null), and all three are 2-group "
      "risk-shape splits whose partitions disagree with every other configuration (median ARI ≈ 0.04). Against column-shuffled nulls, which destroy the correlations, "
      f"{int(T('rq4_existence_null_test').query('units == \"all31\"').beats_shuffle.sum())} of 24 configurations look clustered. Most of the apparent structure is correlation between risks, not groups of states.")
    w(f"* **4b Stability.** The median ARI across the 24 configurations is {a['median_cross_config_ari']:.2f} at each configuration's chosen k, and "
      f"{a['median_cross_config_ari_k3']:.2f} at k = 3. Refits on the uncertainty draws give a median ARI of {a['unc_ari_median_over_configs']:.2f} against the base partition. "
      f"Leave-one-risk-out refits give {a['loro_ari_median_over_configs']:.2f}. "
      + ("No configuration passes gate 2. In none of them is every cluster bootstrap-stable (Jaccard ≥ 0.75) while also agreeing with the other configurations."
         if a['gate2_pass'] == 0 else f"{a['gate2_pass']} configurations pass gate 2."))
    w("* **Stable cores** (consensus co-assignment ≥ 0.70 across all runs). These are robust neighbourhoods on the gradient, not separated clusters:")
    for c in a["cores"]:
        w(f"    * {', '.join(c['states'])} (mean co-assignment {c['mean_coassignment']:.2f})")
    w(f"* No state is a floater (co-assignment < 0.5 with everyone): {a['floaters'] or 'none'}.\n")
    w("**4c Interpretation** (primary configuration: Core, log ASR 2023, z-score, K-means). This is a descriptive partition of a continuum, not a finding of distinct types:\n")
    for k, dd in r4i["profiles"].items():
        w(f"*k = {k}*")
        for c, d in dd.items():
            w(f"* {c} ({len(d['states'])}): {d['description']}. {', '.join(d['states'])}")
        w("")
    p = r4i["pca"]
    w(f"PCA: PC1 explains {p['var'][0]:.0%} of variance and is overall burden level (correlation with the state mean z = {p['corr_pc1_mean_level']:.2f}). "
      f"PC2 ({p['var'][1]:.0%}) contrasts " + ", ".join(short(r) for r in list(p['pc2'])[:3]) + " with " + ", ".join(short(r) for r in list(p['pc2'])[-3:]) + ". "
      f"The pilot's k = 3 grouping is largely reproduced (ARI {r4i['ari_vs_pilot_k3_groups']:.2f}).\n")
    z = r4i["zone"]
    wc = r4i["watchlist_concentration"]
    w(f"**4d External meaning.** Clusters barely follow Zonal Council geography (ARI {z['primary_ari_k3']:.2f} for the primary configuration; median across configurations {z['median_ari_all_configs']:.2f}). "
      "The exception is the north-eastern and hill states, which group together under most settings. The SDI check could not be run because Appendix 1 S12 was not supplied. "
      f"RQ1 watchlist pairs are not concentrated in one cluster (Kruskal–Wallis p = {wc['kruskal_clear_p']:.2f} for clear worsening, p = {wc['kruskal_watch_p']:.2f} for any tier). "
      f"The peer benchmark finds {r4i['peer_benchmark']['n_hidden']} \"hidden divergence\" pairs: at least 10 pp worse than the state's cluster peers, but untiered against India "
      "(`rq4_hidden_divergence.csv`).\n")
    w("**4.8 Profile migration 1990 → 2010 → 2023.**")
    for v in ("shape", "level"):
        m = r4m[v]
        w(f"* *{v}* variant: membership by year "
          + "; ".join(f"{y}: " + ", ".join(f"{k} {n}" for k, n in sorted(c.items())) for y, c in m["membership_by_year"].items())
          + f". {m['n_changed']} of 31 states changed profile between 1990 and 2023. Profiles: "
          + "; ".join(f"{k} = {d}" for k, d in m["profiles"].items()))
    w("\nThe shape variant shows the epidemiological transition directly. Most states start in a profile dominated by malnutrition, unsafe water and air pollution "
      "and end in one dominated by metabolic and dietary risks. Kerala, Goa, Punjab, Delhi and Tamil Nadu were already in the metabolic profile in 1990. "
      "Most southern and western states had shifted by 2010, and Bihar, Uttar Pradesh, Odisha, Jharkhand and Madhya Pradesh by 2023. "
      "Rajasthan is the only state still in the traditional profile in 2023. Five north-eastern states (Arunachal Pradesh, Manipur, Meghalaya, "
      "Mizoram, Sikkim) stay in their own drug, alcohol and tobacco profile throughout. "
      "This change over time is a far stronger structure than any cross-sectional clustering.\n")
    w("Figures: `rq4_existence_all31.png`, `rq4_consensus_all31.png`, `rq4_cross_config_ari.png`, `rq4_cluster_profiles.png`, `rq4_pca_biplot.png`, "
      "`rq4_migration_shape.png` / `_level.png`, and the interactive Sankey diagrams (`rq4_migration_*_sankey.html`).\n")

    w("## Limitations\n")
    w("* These are modelled GBD estimates. Attributable deaths overlap across risks (mediation), so they are never summed.\n"
      "* The uncertainty draws are independent per cell, because IHME's 500 posterior draws are not public. Rank noise is therefore probably overstated.\n"
      "* \"Other Union Territories\" is an aggregate. Every RQ was repeated without it, and the conclusions did not change.\n"
      "* SDI (Appendix 1 S12), the evidence-star ratings (Appendix 2 S8), and S14A/S15A were not supplied.\n"
      f"* {C.DISCLAIMER}\n")
    (C.DOCS / "RESULTS.md").write_text("\n".join(out), encoding="utf-8")
    print(f"  wrote {(C.DOCS / 'RESULTS.md').relative_to(C.ROOT)}")


if __name__ == "__main__":
    main()
